"""Generates src/stubs.cpp: a logging stub for every imported function that kernel.cpp does not implement.
Re-run after adding HOST_FUNC(...) implementations:  python gen_stubs.py"""
import re
import pathlib

here = pathlib.Path(__file__).parent
names_all = []
for line in (here.parent / 'imports.txt').read_text().splitlines():
    line = line.strip()
    # import thunks are named __imp__<Name>; skip _xstart and the __imp____restvmx style internals
    if line.startswith('__imp__') and not line.startswith('__imp____'):
        names_all.append(line[len('__imp__'):])
    elif line.startswith('__imp____C_specific_handler'):
        names_all.append(line[len('__imp__'):])

implemented = set()
for src in (here / 'src').glob('*.cpp'):
    if src.name == 'stubs.cpp':
        continue
    implemented |= set(re.findall(r'HOST_FUNC\((\w+)\)', src.read_text(encoding='utf-8')))

names = sorted(set(names_all) - implemented)
out = [
    '// GENERATED by gen_stubs.py -- do not edit.',
    '#include "guest.h"',
    '#include <atomic>',
    'static void StubLog(const char* n, PPCContext& c, std::atomic<int>& k) {',
    '    if (k++ < 3)',
    '        Log("[stub] %s(%08X, %08X, %08X, %08X) lr=%08llX", n, c.r3.u32, c.r4.u32, c.r5.u32, c.r6.u32, (unsigned long long)c.lr);',
    '}',
]
for n in names:
    out.append(f'HOST_FUNC({n}) {{ static std::atomic<int> k{{0}}; StubLog("{n}", ctx, k); ctx.r3.u64 = 0; }}')
(here / 'src' / 'stubs.cpp').write_text('\n'.join(out) + '\n', encoding='utf-8')
print(len(names), 'stubs generated;', len(implemented), 'implemented')
